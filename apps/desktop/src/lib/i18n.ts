export type Lang = 'ru' | 'en';

export function resolveLang(pref: string | undefined): Lang {
  if (pref === 'ru' || pref === 'en') return pref;
  return (typeof navigator !== 'undefined' && navigator.language.toLowerCase().startsWith('ru')) ? 'ru' : 'en';
}

export const translate = (lang: Lang, k: Key) => (lang === 'ru' ? ru[k] : en[k]);

export function useT() {
  const lang = useApp((s) => resolveLang(s.settings?.language));
  return Object.assign((k: Key) => translate(lang, k), { lang });
}

export const tNow = (k: Key) => translate(resolveLang(useApp.getState().settings?.language), k);

/** Inline bilingual text for one-off strings: tr('Weather', 'Погода'). */
export function useTr() {
  const lang = useApp((s) => resolveLang(s.settings?.language));
  return Object.assign((en: string, ru: string) => (lang === 'ru' ? ru : en), { lang });
}
